RUN_THROUGH_STAGES = ["none", "data_prep", "results"]  # keep in step with lsff_utils.config_utils


def scenario_slug(name):
    """How prep_extracted matches a Scenario to a configured scenario name."""
    return re.sub(r"[\W_]+", "_", str(name).lower())


def read_arms(model_arms_file, lit, decisions):
    """Every arm in the model's arm list, with what to build for it.

    Each arm is a dict: country, vehicle, fortificants, scenarios ({slug: name as written in
    the tables}), modeled (run_through is data_prep or results), hces.
    """
    model_arms_file = pathlib.Path(model_arms_file)
    with open(model_arms_file.parent / "config.yaml") as f:
        config = yaml.safe_load(f)
    all_forts = [canonical(FORTIFICANTS, f)[0] for f in config["all_fortificants"]]
    custom = config.get("custom_intervention_scenarios") or {}

    table = pd.read_csv(model_arms_file, dtype=str).fillna("")
    if "run_through" not in table.columns:
        table["run_through"] = ""
    arms = {}
    for i, a in table.iterrows():
        where = f"{model_arms_file.name} row {i + 2}"
        run_through = norm(a.run_through) or "results"
        if run_through not in RUN_THROUGH_STAGES:
            raise ValueError(f"{where}: unknown run_through '{a.run_through}' "
                             f"(expected one of {', '.join(RUN_THROUGH_STAGES)}, or blank)")
        country, vehicle = canonical(COUNTRIES, a.location)[0], canonical(VEHICLES, a.vehicle)[0]
        if country is None or vehicle is None:
            raise ValueError(f"{where}: unknown location or vehicle '{a.location}' / '{a.vehicle}'")
        if norm(a.fortificant) == "all":
            forts = all_forts
        else:
            fort = canonical(FORTIFICANTS, a.fortificant)[0]
            if fort is None:
                raise ValueError(f"{where}: unknown fortificant '{a.fortificant}'")
            forts = [fort]
        arm = arms.setdefault((country, vehicle), {
            "country": country, "vehicle": vehicle, "fortificants": set(), "modeled": False,
            "hces": (country, vehicle) in HCES_ARMS,
            "slugs": list((custom.get(norm(a.location)) or {}).get(norm(a.vehicle)) or ["intervention"]),
        })
        arm["fortificants"].update(forts)
        arm["modeled"] = arm["modeled"] or run_through != "none"

    out = []
    for (country, vehicle), arm in sorted(arms.items()):
        names = scenario_names(country, vehicle, lit, decisions)
        scenarios = {}
        for slug in arm.pop("slugs"):
            if slug not in names:
                raise ValueError(f"{country} {vehicle}: scenario '{slug}' (config.yaml) isn't named by any "
                                 "literature row or decision, so its rows can't be labelled. Add its rows to "
                                 "the literature workbook, or a decision with the scenario's full name.")
            scenarios[slug] = names[slug]
        out.append({**arm, "fortificants": sorted(arm["fortificants"]), "scenarios": scenarios})
    return out


def scenario_names(country, vehicle, lit, decisions):
    """{slug: Scenario as written} from the literature and decisions for an arm."""
    names = {"intervention": "Intervention"}
    found = list(lit[(lit.country == country) & (lit.vehicle == vehicle)].scenario.dropna())
    found += list(decisions[(decisions.country == country) & (decisions.vehicle == vehicle)].scenario)
    for name in found:
        if str(name).strip():
            names.setdefault(scenario_slug(name), " ".join(str(name).split()))
    return names


