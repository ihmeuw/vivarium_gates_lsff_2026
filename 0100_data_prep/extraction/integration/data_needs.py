def _source_strata(need, arm, fortificant, scenario, lit, gf, decisions):
    """(quintiles, sexes, method_decision) that the sources give for one group of rows."""
    quintiles, sexes = set(), set()
    c, v = arm["country"], arm["vehicle"]
    usable = lit[(lit.status == "ok") & (lit.need == need.alias) & (lit.vehicle == v)]
    usable = usable[usable.data_point_name.map(norm) == norm(need.data_point)]
    if need.table != VEH:
        usable = usable[usable.country == c]
    if need.table in (CVF, SCEN):
        usable = usable[usable.fortificant == fortificant]
    if need.table == SCEN:
        usable = usable[usable.scenario.map(lambda s: scenario_slug(s) if str(s).strip() and s == s else "")
                        .isin([scenario_slug(scenario), ""])]
    for _, r in usable.iterrows():
        if r.use_in_model == "no":
            continue
        quintiles.add(r.quintile if isinstance(r.quintile, str) and r.quintile else "Total")
        if isinstance(r.sex, str) and r.sex:
            sexes.add(r.sex)

    if gf is not None and need.alias in ("any", "amount") and norm(need.data_point) in ("percentage", "mean"):
        metric = "coverage" if need.alias == "any" else "g_per_capita"
        by_q = gf.by_quintile(c, v, metric)
        if all(val is not None for val, _ in by_q.values()):
            quintiles.update(QUINTILES)
        if gf.national(c, v, metric)[0] is not None:
            quintiles.add("Total")

    method = False
    active = decisions[decisions.status == "active"]
    for _, d in active.iterrows():
        if need_alias(d.need) != need.alias:
            continue
        if need.table != VEH and d.country and d.country != c:
            continue
        if d.vehicle and d.vehicle != v:
            continue
        if d.data_point_name and norm(d.data_point_name) != norm(need.data_point):
            continue
        if need.table in (CVF, SCEN) and d.fortificant and d.fortificant != fortificant:
            continue
        if need.table == SCEN and d.scenario and scenario_slug(d.scenario) != scenario_slug(scenario):
            continue
        if d.quintile:
            quintiles.add(d.quintile)
        if d.sex:
            sexes.add(d.sex)
        method = method or d.source.startswith("method:")
    return quintiles, sexes, method


def _quintile_layout(need, arm, quintiles):
    if need.quintiles == "total" or (need.alias == "fortifiability" and arm["hces"]):
        return ["Total"]
    if set(QUINTILES) <= quintiles:
        return (["Total"] if "Total" in quintiles else []) + QUINTILES
    return [ALL_SAME]


def _sex_layout(need, sexes):
    if need.table != CV:
        return [None]
    if need.sex != "data":
        return [need.sex]
    if {"Female", "Male"} <= sexes:
        return ["Female", "Male"] + (["Total"] if "Total" in sexes else [])
    return [ALL_SAME]


def skeleton(arms, lit, gf, decisions):
    """Empty rows for every listed arm: ({table: DataFrame}, {(table, line): row info}).

    Row info: arm (country, vehicle), modeled, required.
    """
    rows = {t: [] for t in TABLE_COLUMNS}
    vehicles = {}  # vehicle -> modeled by any arm
    for arm in arms:
        vehicles[arm["vehicle"]] = vehicles.get(arm["vehicle"], False) or arm["modeled"]
        mean_layouts = {}
        for need in SPEC:
            if need.table == VEH or not need.applies(arm):
                continue
            forts = arm["fortificants"] if need.table in (CVF, SCEN) else [None]
            for f in forts:
                scenarios = list(arm["scenarios"].values()) if need.table == SCEN else [None]
                for s in scenarios:
                    qs, sexes, method = _source_strata(need, arm, f, s, lit, gf, decisions)
                    required = need.required(arm)
                    if not required and not qs and not sexes:
                        continue  # optional, and nothing would fill it
                    layout = _quintile_layout(need, arm, qs)
                    if norm(need.data_point) == "mean":
                        mean_layouts[need.alias] = layout
                    elif (method and layout == [ALL_SAME] and
                          QUINTILES[0] in mean_layouts.get(need.alias, [])):
                        # A method computes SDs row by row from the means, so it needs their split
                        layout = mean_layouts[need.alias]
                    if QUINTILES[0] in layout and "Total" not in layout:
                        layout = ["Total"] + layout
                    for q in layout:
                        for sex in _sex_layout(need, sexes):
                            rows[need.table].append({
                                "Country": arm["country"], "Vehicle": arm["vehicle"], "Fortificant": f,
                                "Scenario": s, "Quintile": q, "Sex": sex, "Data need": need.text,
                                "Data point name": need.data_point, "Units": need.units,
                                "_arm": (arm["country"], arm["vehicle"]), "_modeled": arm["modeled"],
                                "_required": required,
                            })
    for vehicle, modeled in sorted(vehicles.items()):
        for need in SPEC:
            if need.table == VEH:
                rows[VEH].append({"Vehicle": vehicle, "Data need": need.text, "Data point name": need.data_point,
                                  "Units": need.units, "_arm": (None, vehicle), "_modeled": modeled,
                                  "_required": modeled})

    frames, info = {}, {}
    spec_order = {(n.alias, n.data_point): i for i, n in enumerate(SPEC)}
    for t, recs in rows.items():
        df = pd.DataFrame(recs)
        df["_need"] = [spec_order[(need_alias(n), p)] for n, p in zip(df["Data need"], df["Data point name"])]
        sort = [c for c in ["Country", "Vehicle", "_need", "Fortificant", "Scenario"] if c in df.columns]
        if "Quintile" in df.columns:
            df["_q"] = df.Quintile.map(QUINTILE_ORDER)
            sort.append("_q")
        if t == CV:
            df["_s"] = df.Sex.map(SEX_ORDER)
            sort.append("_s")
        df = df.sort_values(sort, kind="stable").reset_index(drop=True)
        for i, r in df.iterrows():
            info[(t, i + 2)] = {"arm": r["_arm"], "modeled": r["_modeled"], "required": r["_required"]}
        out = pd.DataFrame({c: (df[c] if c in df.columns else "") for c in TABLE_COLUMNS[t]})
        frames[t] = out.fillna("").astype(str)
    return frames, info


def write_spec_markdown(path):
    """DATA_NEEDS.md: the spec as a readable table (regenerated by every build)."""
    df = spec_table()
    lines = ["# Data needs", "",
             "Generated from `SPEC` in `data_needs.py` by `build_extraction.py`; do not edit. Every arm "
             "the model runs gets rows for each need that applies to it (per fortificant, and per "
             "configured scenario in `scenario_definition`). How each group of rows is split, and which "
             "rows are required, is described in `data_needs.py`.", "",
             "| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v).replace("|", "/") for v in r) + " |")
    pathlib.Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def spec_table():
    """The spec as a table, for DATA_NEEDS.md."""
    def who(f):
        return {_always: "all", _not_hces: "all but HCES arms", _nigeria: "Nigeria", _never: "none"}[f]
    return pd.DataFrame([{
        "table": n.table, "data need": n.text, "data point": n.data_point, "units": n.units,
        "applies to": who(n.applies) if n.table != VEH else "each vehicle",
        "required for": who(n.required) if n.table != VEH else "vehicles of arms the model runs",
        "split": {"data": "5 quintiles + Total, or one 'All (assumed same)'", "total": "one 'Total'"}[n.quintiles]
        if n.table in (CV, CVF) else "one row",
        "read by": n.read_by, "notes": n.notes,
    } for n in SPEC])
