"""Validate the generated extraction tables (0100_data_prep/extraction/generated/).

Note: this code was generated by an AI assistant (Claude) and has not been carefully
reviewed by a human.
"""

import csv
from pathlib import Path

import pytest

from lsff_utils import extraction
from lsff_utils.extraction import TABLES, extraction_path, load_extraction

# Relative to this file, not paths.REPO_ROOT: CI installs lsff_utils
# non-editable, so REPO_ROOT points into site-packages.
EXTRACTION_DIR = Path(__file__).resolve().parents[1] / "0100_data_prep" / "extraction"
EXTRACTION_GENERATED_DIR = EXTRACTION_DIR / "generated"


@pytest.fixture(autouse=True)
def checkout_extraction_dirs(monkeypatch):
    monkeypatch.setattr(extraction, "EXTRACTION_GENERATED_DIR", EXTRACTION_GENERATED_DIR)


def test_every_csv_is_a_known_table():
    assert {p.stem for p in EXTRACTION_GENERATED_DIR.glob("*.csv")} == set(TABLES)


def test_old_extraction_sheet_is_gone():
    """The build no longer reads extraction/data/; nothing should come back there by accident."""
    assert not (EXTRACTION_DIR / "data").exists()


@pytest.mark.parametrize("table", TABLES)
def test_table_loads_and_validates(table):
    df = load_extraction(table)
    assert len(df) > 0


@pytest.mark.parametrize("table", TABLES)
def test_rows_have_header_width(table):
    with open(extraction_path(table), newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    widths = {len(r) for r in rows}
    assert widths == {len(rows[0])}, f"{table}.csv has rows of widths {sorted(widths)}"
