LIT_COLUMNS = [
    "lit_id",
    "status",
    "need",
    "country",
    "vehicle",
    "fortificant",
    "scenario",
    "quintile",
    "sex",
    "data_point_name",
    "value",
    "use_in_model",
]
DECISION_COLUMNS = [
    "decision_id",
    "status",
    "need",
    "country",
    "vehicle",
    "fortificant",
    "scenario",
    "quintile",
    "sex",
    "data_point_name",
    "source",
]


def lit(*rows):
    return pd.DataFrame([dict(zip(LIT_COLUMNS, r)) for r in rows], columns=LIT_COLUMNS)


def decisions(*rows):
    return pd.DataFrame(
        [dict(zip(DECISION_COLUMNS, r)) for r in rows], columns=DECISION_COLUMNS
    ).fillna("")


def arm(
    country="Nigeria",
    vehicle="Wheat",
    fortificants=("Iron",),
    modeled=True,
    hces=False,
    scenarios=None,
):
    return {
        "country": country,
        "vehicle": vehicle,
        "fortificants": list(fortificants),
        "modeled": modeled,
        "hces": hces,
        "scenarios": scenarios or {"intervention": "Intervention"},
    }


def rows(frames, table, need_text=None, **match):
    df = frames[table]
    if need_text is not None:
        df = df[df["Data need"] == need_text]
    for k, v in match.items():
        df = df[df[k] == v]
    return df


ANY = "Vehicle consumption by WRA -- any"
AMOUNT = "Vehicle consumption by WRA -- amount"


def test_quintile_rows_when_a_source_has_all_five():
    quintile_rows = [
        (
            f"l{i}",
            "ok",
            "any",
            "Nigeria",
            "Wheat",
            None,
            None,
            q,
            "Female",
            "percentage",
            0.3,
            None,
        )
        for i, q in enumerate(["Total"] + QUINTILES)
    ]
    frames, _ = data_needs.skeleton([arm()], lit(*quintile_rows), None, decisions())
    assert list(rows(frames, CV, ANY).Quintile) == ["Total"] + QUINTILES
    assert set(rows(frames, CV, ANY).Sex) == {"Female"}


