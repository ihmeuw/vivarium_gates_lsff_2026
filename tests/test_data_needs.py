def test_rows_per_fortificant_and_scenario():
    a = arm(
        fortificants=("Folate", "Iron"),
        scenarios={
            "intervention_25_nrv": "Intervention - 25% NRV",
            "intervention_100_nrv": "Intervention - 100% NRV",
        },
    )
    frames, _ = data_needs.skeleton([a], lit(), None, decisions())
    assert set(frames[CVF].Fortificant) == {"Folate", "Iron"}
    assert len(frames[SCEN]) == 2 * 2 * 3  # fortificants x scenarios x needs
    assert set(frames[SCEN].Scenario) == {"Intervention - 25% NRV", "Intervention - 100% NRV"}


def test_optional_needs_appear_only_with_a_source():
    frames, _ = data_needs.skeleton([arm()], lit(), None, decisions())
    assert rows(frames, CV, "Vehicle consumption by U5 children -- any").empty
    u5 = (
        "l1",
        "ok",
        "u5_any",
        "Nigeria",
        "Wheat",
        None,
        None,
        "Total",
        "Total",
        "percentage",
        0.3,
        None,
    )
    frames, info = data_needs.skeleton([arm()], lit(u5), None, decisions())
    u5_rows = rows(frames, CV, "Vehicle consumption by U5 children -- any")
    assert len(u5_rows) == 1
    assert not info[(CV, u5_rows.index[0] + 2)]["required"]


def test_vehicle_rows_required_only_for_arms_the_model_runs():
    frames, info = data_needs.skeleton(
        [arm(vehicle="Wheat"), arm(vehicle="Salt", modeled=False)], lit(), None, decisions()
    )
    required = {
        frames[VEH].at[line - 2, "Vehicle"]
        for (t, line), r in info.items()
        if t == VEH and r["required"]
    }
    assert required == {"Wheat"}


def test_empty_required_rows_are_reported():
    frames, info = data_needs.skeleton([arm()], lit(), None, decisions())
    wb = Workbook(frames=frames)
    missing = build_extraction.missing_rows(wb, info)
    assert (CV, rows(frames, CV, ANY).index[0] + 2) in missing
    # an arm the model doesn't run isn't checked
    frames, info = data_needs.skeleton([arm(modeled=False)], lit(), None, decisions())
    assert build_extraction.missing_rows(Workbook(frames=frames), info) == []


