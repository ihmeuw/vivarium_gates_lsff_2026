EXTRACTION_DIR = Path(__file__).resolve().parents[1] / "0100_data_prep" / "extraction"
EXTRACTION_GENERATED_DIR = EXTRACTION_DIR / "generated"
INTEGRATION_DIR = EXTRACTION_DIR / "integration"


