"""
=========================
Data prep results checks
=========================

Check the CSVs that ``0100_data_prep`` writes to ``0100_data_prep/results/`` (from the
extraction tables, from HCES microdata and from the coverage notebook) before anything
downstream reads them. Snakemake runs :func:`check_files` on every data prep results file
of the arms that run (rule ``check_data_prep_results``); a problem stops the run.

Every file must have a ``value`` column with finite, non-negative values. Shares
(coverage, effectiveness, fortifiability) must be in [0, 1]. Files split by wealth
quintile must have each of the five quintiles exactly once for every other combination
of columns (sex, age group, ...).

Note: this code was generated by an AI assistant (Claude) and underwent
human review and approval in
https://github.com/ihmeuw/vivarium_gates_lsff_2026/pull/70
"""

from pathlib import Path

import numpy as np
import pandas as pd

from lsff_utils.data_processing import WEALTH_QUINTILES

# Path fragments of results files whose values are shares
SHARE_PARTS = (
    "any_coverage",
    "full_coverage",
    "effective_coverage",
    "effectiveness",
    "fortifiability",
    "vehicle_consumption/any",
)

# Columns we don't want to group by when checking that all wealth
# quintiles exist. The remaining "key" columns describe the stratum
# (sex, age, etc.)
NON_KEY_COLUMNS = {"value", "wealth_quintile", "vehicle_name"}


def is_share(path) -> bool:
    text = Path(path).as_posix()
    return any(f"/{part}/" in text for part in SHARE_PARTS)


def check_file(path) -> list[str]:
    """Problems with one results file (empty if none)."""
    path = Path(path)
    if not path.exists():
        return [f"{path}: missing"]
    try:
        df = pd.read_csv(path)
    except Exception as e:  # unreadable or empty file
        return [f"{path}: can't be read ({e})"]
    if df.empty:
        return [f"{path}: no rows"]
    if "value" not in df.columns:
        return [f"{path}: no 'value' column (columns: {', '.join(df.columns)})"]

    problems = []
    value = pd.to_numeric(df["value"], errors="coerce")
    if value.isna().any():
        problems.append(f"{path}: {int(value.isna().sum())} missing or non-numeric values")
    finite = value.dropna()
    if not np.isfinite(finite).all():
        problems.append(f"{path}: infinite values")
    if (finite < 0).any():
        problems.append(f"{path}: negative values (min {finite.min():g})")
    if is_share(path) and (finite > 1).any():
        problems.append(f"{path}: shares above 1 (max {finite.max():g})")

    if "wealth_quintile" in df.columns:
        keys = [c for c in df.columns if c not in NON_KEY_COLUMNS]
        groups = df.groupby(keys, dropna=False) if keys else [((), df)]
        expected = sorted(WEALTH_QUINTILES)
        for key, group in groups:
            found = sorted(pd.to_numeric(group["wealth_quintile"], errors="coerce").tolist())
            if found != expected:
                where = (
                    f" for {dict(zip(keys, key if isinstance(key, tuple) else (key,)))}"
                    if keys
                    else ""
                )
                problems.append(
                    f"{path}: wealth quintiles {found}{where}, expected {expected} once each"
                )
                break  # one example per file is enough
    return problems


def check_files(paths) -> list[str]:
    """Problems with all of ``paths`` (empty if none)."""
    problems = []
    for path in paths:
        problems += check_file(path)
    return problems
